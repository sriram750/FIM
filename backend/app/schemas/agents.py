from pydantic import BaseModel, Field
from typing import Optional, List, Dict, Any
from datetime import datetime


class AgentEnrollRequest(BaseModel):
    hostname: str = Field(..., min_length=1, max_length=255)
    domain: Optional[str] = None
    ip_address: Optional[str] = None
    mac_address: Optional[str] = None
    os_name: str = "Windows"
    os_version: Optional[str] = None
    os_build: Optional[str] = None
    agent_version: str = "1.0.0"
    enrollment_token: str = Field(..., description="Pre-shared enrollment authorization secret")


class AgentEnrollResponse(BaseModel):
    endpoint_id: str
    token: str
    hostname: str
    status: str
    message: str


class AgentHeartbeatRequest(BaseModel):
    queue_depth: int = 0
    disk_usage_bytes: int = 0
    cpu_percent: float = 0.0
    memory_percent: float = 0.0
    watcher_status: str = "active"
    audit_collector_status: str = "active"
    policy_version: int = 1


class AgentHeartbeatResponse(BaseModel):
    status: str = "ok"
    acknowledged_at: datetime
    policy_version_expected: int = 1


class EventBatchItem(BaseModel):
    event_id: str = Field(..., description="UUID generated by the endpoint")
    sequence_number: int = Field(..., ge=0)
    event_type: str = Field(..., description="file_created, file_modified, file_deleted, file_renamed, baseline_created, integrity_mismatch, watcher_overflow")
    file_path: str
    old_file_path: Optional[str] = None
    file_name: str
    file_size_bytes: int = 0
    sha256_hash: Optional[str] = None
    old_sha256_hash: Optional[str] = None
    event_timestamp: datetime
    source: str = "watcher"
    severity: str = "info"
    schema_version: str = "1.0"
    extra_metadata: Optional[Dict[str, Any]] = None


class AgentEventsBatchRequest(BaseModel):
    events: List[EventBatchItem]


class AgentEventsBatchResponse(BaseModel):
    acknowledged_event_ids: List[str]
    count: int
    received_at: datetime


class MonitoredPathConfig(BaseModel):
    path: str
    is_recursive: bool = True
    track_attributes: bool = True
    hash_algorithm: str = "SHA-256"


class AgentConfigResponse(BaseModel):
    endpoint_id: str
    policy_name: str
    policy_version: int
    scan_interval_seconds: int
    hash_on_create: bool
    hash_on_modify: bool
    max_file_size_mb: int
    audit_collection_enabled: bool
    monitored_paths: List[MonitoredPathConfig]
    exclusions: List[Dict[str, str]]
